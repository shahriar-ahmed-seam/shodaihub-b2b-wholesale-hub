/**
 * Fetch wholesale-relevant photography from the Unsplash API and generate
 * src/lib/mock/images.generated.ts (hero + per-category image pools with attribution).
 *
 * Usage (from the `frontend` directory):
 *   UNSPLASH_ACCESS_KEY=xxxx node scripts/fetch-unsplash.mjs
 *   # or: node scripts/fetch-unsplash.mjs <ACCESS_KEY>
 *   # or set UNSPLASH_ACCESS_KEY in frontend/.env.local and run: npm run fetch:images
 *
 * Unsplash API Guidelines compliance:
 *   - images are hotlinked via the returned images.unsplash.com URLs (never re-hosted);
 *   - each image keeps photographer attribution (name + profile link with UTM);
 *   - the photo "download" endpoint is triggered for every selected photo (best-effort).
 *
 * Demo Unsplash apps are rate-limited to 50 requests/hour. The script does all searches first
 * (so the catalogue is populated), then triggers downloads best-effort, tolerating 403/429.
 */

import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_FILE = path.join(__dirname, '..', 'src', 'lib', 'mock', 'images.generated.ts');
const ENV_FILE = path.join(__dirname, '..', '.env.local');

const API = 'https://api.unsplash.com';
const UTM = '?utm_source=b2b_wholesale_hub&utm_medium=referral';

/** Per-category Unsplash search queries (category slug -> primary search term). */
const CATEGORY_QUERIES = {
  'food-grains': 'rice sacks grain bags',
  textiles: 'colorful fabric textile rolls',
  beverages: 'tea leaves and bottled drinks',
  'home-kitchen': 'ceramic plates kitchenware',
  'eco-packaging': 'jute bags sacks packaging',
  electronics: 'light bulbs electronics accessories',
  construction: 'cement bags construction materials',
  'health-beauty': 'soap cosmetics personal care',
};

const HERO_QUERY = 'wholesale market warehouse trade';

const PER_CATEGORY = 6;
const HERO_COUNT = 3;

async function readKey() {
  const fromArg = process.argv[2];
  if (fromArg && fromArg.trim()) return fromArg.trim();
  if (process.env.UNSPLASH_ACCESS_KEY) return process.env.UNSPLASH_ACCESS_KEY.trim();
  try {
    const env = await readFile(ENV_FILE, 'utf8');
    const m = env.match(/^UNSPLASH_ACCESS_KEY\s*=\s*(.+)$/m);
    if (m && m[1].trim()) return m[1].trim().replace(/^["']|["']$/g, '');
  } catch {
    /* no .env.local */
  }
  return null;
}

function sized(raw, params) {
  const sep = raw.includes('?') ? '&' : '?';
  return `${raw}${sep}${params}`;
}

function toImage(photo) {
  const raw = photo.urls.raw;
  return {
    url: sized(raw, 'w=900&h=675&fit=crop&q=80&fm=jpg&auto=format'),
    thumb: sized(raw, 'w=320&h=240&fit=crop&q=70&fm=jpg&auto=format'),
    alt: photo.alt_description || photo.description || 'Wholesale product',
    authorName: photo.user?.name || 'Unsplash',
    authorUrl: (photo.user?.links?.html || 'https://unsplash.com') + UTM,
    _download: photo.links?.download_location || null,
  };
}

function toHero(photo) {
  const raw = photo.urls.raw;
  return {
    url: sized(raw, 'w=3840&q=80&fm=jpg&auto=format&fit=max'),
    thumb: sized(raw, 'w=480&h=360&fit=crop&q=70&fm=jpg&auto=format'),
    alt: photo.alt_description || photo.description || 'Bangladeshi wholesale marketplace',
    authorName: photo.user?.name || 'Unsplash',
    authorUrl: (photo.user?.links?.html || 'https://unsplash.com') + UTM,
    _download: photo.links?.download_location || null,
  };
}

async function search(key, query, perPage, orientation = 'landscape') {
  const url = `${API}/search/photos?query=${encodeURIComponent(query)}&per_page=${perPage}&orientation=${orientation}&content_filter=high`;
  const res = await fetch(url, { headers: { Authorization: `Client-ID ${key}`, 'Accept-Version': 'v1' } });
  const remaining = res.headers.get('x-ratelimit-remaining');
  if (!res.ok) {
    const body = await res.text();
    throw new Error(`search "${query}" -> ${res.status} ${res.statusText} (remaining=${remaining}) ${body.slice(0, 160)}`);
  }
  const json = await res.json();
  return { results: json.results ?? [], remaining };
}

async function triggerDownload(key, downloadLocation) {
  if (!downloadLocation) return;
  try {
    await fetch(`${downloadLocation}&client_id=${key}`, { headers: { 'Accept-Version': 'v1' } });
  } catch {
    /* best-effort */
  }
}

function serialize(heroImages, categoryImages) {
  const strip = ({ _download, ...rest }) => rest; // drop internal field from output
  const hero = heroImages.map(strip);
  const cats = Object.fromEntries(Object.entries(categoryImages).map(([k, v]) => [k, v.map(strip)]));
  const header = `/**
 * AUTO-GENERATED by scripts/fetch-unsplash.mjs — DO NOT EDIT BY HAND.
 * Photography from Unsplash (https://unsplash.com), hotlinked per the Unsplash API Guidelines.
 * Re-run \`npm run fetch:images\` to refresh.
 */

export interface UnsplashImage {
  url: string;
  thumb: string;
  alt: string;
  authorName: string;
  authorUrl: string;
}

`;
  return (
    header +
    `export const HERO_IMAGES: UnsplashImage[] = ${JSON.stringify(hero, null, 2)};\n\n` +
    `export const CATEGORY_IMAGES: Record<string, UnsplashImage[]> = ${JSON.stringify(cats, null, 2)};\n`
  );
}

async function main() {
  const key = await readKey();
  if (!key) {
    console.error(
      '\nMissing Unsplash Access Key.\n' +
        'Provide it via: UNSPLASH_ACCESS_KEY=<key> node scripts/fetch-unsplash.mjs\n' +
        'or add UNSPLASH_ACCESS_KEY=<key> to frontend/.env.local, then `npm run fetch:images`.\n',
    );
    process.exit(1);
  }

  console.log('Fetching hero photography...');
  const heroRes = await search(key, HERO_QUERY, HERO_COUNT, 'landscape');
  const heroImages = heroRes.results.slice(0, HERO_COUNT).map(toHero);
  console.log(`  hero: ${heroImages.length} (ratelimit remaining=${heroRes.remaining})`);

  const categoryImages = {};
  for (const [slug, query] of Object.entries(CATEGORY_QUERIES)) {
    try {
      let { results, remaining } = await search(key, query, PER_CATEGORY + 2, 'squarish');
      // Self-heal: some queries return nothing under 'squarish'; retry once as 'landscape'.
      if (results.length === 0) {
        ({ results, remaining } = await search(key, query, PER_CATEGORY + 2, 'landscape'));
      }
      categoryImages[slug] = results.slice(0, PER_CATEGORY).map(toImage);
      console.log(`  ${slug}: ${categoryImages[slug].length} (remaining=${remaining})`);
    } catch (e) {
      console.warn(`  ${slug}: FAILED -> ${e.message}`);
      categoryImages[slug] = [];
    }
  }

  // Write the catalogue BEFORE downloads so images are populated even if downloads get throttled.
  await writeFile(OUT_FILE, serialize(heroImages, categoryImages), 'utf8');
  console.log(`\nWrote ${path.relative(process.cwd(), OUT_FILE)}`);

  // Best-effort download triggers (Unsplash guideline). Tolerates rate limiting.
  console.log('Triggering Unsplash download endpoints (best-effort)...');
  const all = [...heroImages, ...Object.values(categoryImages).flat()];
  let done = 0;
  for (const img of all) {
    await triggerDownload(key, img._download);
    done += 1;
  }
  console.log(`  triggered ~${done} downloads.`);
  console.log('\nDone. Restart `next dev` (or rebuild) to see the photography.');
}

main().catch((e) => {
  console.error('fetch-unsplash failed:', e.message);
  process.exit(1);
});
